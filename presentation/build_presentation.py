def cm(value: float) -> Emu:
    return Emu(int(value * 360000))


def text_box(slide, x, y, w, h, lines, size=16, color=TEXT, bold=False, align=PP_ALIGN.LEFT):
    box = slide.shapes.add_textbox(x, y, w, h)
    frame = box.text_frame
    frame.word_wrap = True
    for i, line in enumerate([lines] if isinstance(lines, str) else lines):
        p = frame.paragraphs[0] if i == 0 else frame.add_paragraph()
        p.alignment = align
        run = p.add_run()
        run.text = line
        run.font.name = FONT
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color
        p.space_after = Pt(4)
    return box


def new_slide(title: str, thesis: str = "", source: str = "", notes: str = ""):
    slide = prs.slides.add_slide(BLANK)
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = BG
    text_box(slide, cm(1.2), cm(0.6), cm(30), cm(1.2), "По Следу", size=12, color=MUTED, bold=True)
    text_box(slide, cm(1.2), cm(1.3), cm(31), cm(1.6), title, size=28, color=ACCENT, bold=True)
    if thesis:
        text_box(slide, cm(1.2), cm(2.9), cm(31), cm(1.4), thesis, size=16, color=TEXT)
    if source:
        text_box(slide, cm(1.2), cm(17.9), cm(31), cm(0.8), f"Источник: {source}", size=10, color=MUTED)
    if notes:
        slide.notes_slide.notes_text_frame.text = notes
    return slide


def table(slide, x, y, w, rows, col_widths=None, size=11, row_h=0.8):
    shape = slide.shapes.add_table(len(rows), len(rows[0]), x, y, w, cm(row_h * len(rows)))
    tbl = shape.table
    if col_widths:
        total = sum(col_widths)
        for i, cw in enumerate(col_widths):
            tbl.columns[i].width = Emu(int(w * cw / total))
    for r, row in enumerate(rows):
        for c, value in enumerate(row):
            cell = tbl.cell(r, c)
            cell.fill.solid()
            cell.fill.fore_color.rgb = ACCENT if r == 0 else PANEL
            cell.margin_left = cell.margin_right = cm(0.15)
            cell.margin_top = cell.margin_bottom = cm(0.05)
            frame = cell.text_frame
            frame.word_wrap = True
            frame.paragraphs[0].text = ""
            run = frame.paragraphs[0].add_run()
            run.text = str(value)
            run.font.name = FONT
            run.font.size = Pt(size)
            run.font.bold = r == 0
            run.font.color.rgb = BG if r == 0 else TEXT
    return tbl


def picture(slide, path: Path, x, y, h=None, w=None):
    return slide.shapes.add_picture(str(path), x, y, width=w, height=h)


